const extensionCategories = new Map<string, FileCategory>();
for (const [category, extensions] of EXTENSION_GROUPS) {
  for (const extension of extensions) {
    // 与桌面端 TryAdd 一致：.key 优先归入密钥，.ts 优先归入代码。
    if (!extensionCategories.has(extension)) extensionCategories.set(extension, category);
  }
}

/** 根据文件名或路径的扩展名分类，规则与桌面客户端保持一致。 */
export function classifyFileName(fileName?: string): FileCategory {
  if (!fileName) return 'File';

  const name = fileName.split(/[\\/]/).pop() ?? '';
  if (!name) return 'File';
  const dot = name.lastIndexOf('.');
  if (dot < 0 || dot === name.length - 1) return 'Binary';
  return extensionCategories.get(name.slice(dot).toLowerCase()) ?? 'File';
}
